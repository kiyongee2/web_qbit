
// 산술 연산자
let x = 10;
let y = 3;    
console.log("x + y = " + (x + y)); // 13
console.log("x - y = " + (x - y)); // 7
console.log("x * y = " + (x * y)); // 30
console.log("x / y = " + (x / y)); // 3.3333...
console.log("x % y = " + (x % y)); // 1
console.log("x ** y = " + (x ** y)); // 1000   

//증감 연산자
let b = 5;
console.log("b = " + b);  // 5
console.log("++b = " + (++b));  // 6 (전위 증가)
console.log("b++ = " + (b++));  // 6 (후위 증가)
console.log("b = " + b);  // 7

let c = 5;
console.log("c = " + c);  // 5
console.log("--c = " + (--c));  // 4 (전위 감소)
console.log("c-- = " + (c--));  // 4 (후위 감소)
console.log("c = " + c);  // 3

// 복합 대입 연산자
let val = 10;
val += 5;  // val = val + 5
console.log("val += 5 => " + val); // 15
val -= 3;  // val = val - 3
console.log("val -= 3 => " + val); // 12
val *= 2;  // val = val * 2
console.log("val *= 2 => " + val); // 24
val /= 4;  // val = val / 4
console.log("val /= 4 => " + val); // 6
val %= 4;  // val = val % 4
console.log("val %= 4 => " + val); // 2
val **= 3;  // val = val ** 3
console.log("val **= 3 => " + val); // 8    



  